"""Adds the optional Jade plugins and the dev-only viewer dependencies to every NeoForge layer of BarelyPowered and BarelyCables.

Run once from the repo root: python scripts/add_jade.py
Writes <layer>/src/main/java/.../jade/*JadePlugin.java from scripts/templates and appends a viewers block to each layer's build.gradle.
Forge layers have no Jade build; they only get the viewer dependencies (JEI and BEI).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARK = "// --- Optional integrations (generated by scripts/add_jade.py) ---"

# Newest file per Minecraft version and loader from the CurseForge lookup of 2026-11-05.
JADE = {"1.21.1": "8591319", "26.1.2": "9156414", "26.2": "8755115", "26.3": "9042207"}
VIEWERS = {
    "neoforge": {
        "1.21.1": {"jade": "jade-324717:8591319", "jei": "jei-238222:9393327", "rei": "roughly-enough-items-310111:6199140",
                   "emi": "emi-580555:8081408", "bei": "bei-1783910:9438917", "architectury": "architectury-api-419699:8492726", "cloth": "cloth-config-348521:5729127"},
        "26.1.2": {"jade": "jade-324717:9156414", "jei": "jei-238222:9384706", "rei": "roughly-enough-items-310111:8271478",
                   "bei": "bei-1783910:9438907", "architectury": "architectury-api-419699:9111154", "cloth": "cloth-config-348521:7817583"},
        "26.2": {"jade": "jade-324717:8755115", "jei": "jei-238222:9352384", "rei": "roughly-enough-items-310111:8271756",
                 "bei": "bei-1783910:9451209", "architectury": "architectury-api-419699:9111233", "cloth": "cloth-config-348521:8269700"},
        "26.3": {"jade": "jade-324717:9042207", "jei": "jei-238222:9453343", "rei": "roughly-enough-items-310111:9090699",
                 "bei": "bei-1783910:9451197", "architectury": "architectury-api-419699:9111315", "cloth": "cloth-config-348521:8952995"},
    },
    "forge": {
        "1.21.1": {"jei": "jei-238222:9393325", "bei": "bei-1783910:9438915"},
        "26.1.2": {"bei": "bei-1783910:9438905"},
        "26.2": {"bei": "bei-1783910:9451199"},
        "26.3": {"bei": "bei-1783910:9451187"},
    },
}

HELPERS_OLD = """    private static String str(CompoundTag data, String key) {
        return data.getString(key);
    }

    private static int num(CompoundTag data, String key) {
        return data.getInt(key);
    }

    private static int[] arr(CompoundTag data, String key) {
        return data.getIntArray(key);
    }"""
HELPERS_NEW = """    private static String str(CompoundTag data, String key) {
        return data.getStringOr(key, "");
    }

    private static int num(CompoundTag data, String key) {
        return data.getIntOr(key, 0);
    }

    private static int[] arr(CompoundTag data, String key) {
        return data.getIntArray(key).orElse(new int[0]);
    }"""

WINDOW_NEO = """// -PwindowSize=1904x1041 opens the dev client at that size (the screenshot checks need the same layout every run).
if (project.hasProperty('windowSize')) {
    neoForge {
        runs {
            client {
                programArgument '--width'
                programArgument project.property('windowSize').split('x')[0]
                programArgument '--height'
                programArgument project.property('windowSize').split('x')[1]
            }
        }
    }
}

"""

BLOCK = MARK + """
// Dev and compile-only access to the optional mods. Nothing here ships: the release jars only hold our own classes, and each
// integration loads only when the other mod is installed. -Pviewers=jade,jei,rei,emi,bei adds those mods to the dev client.
repositories {
    def imcUser = System.getenv('IMC_MAVEN_USER') ?: project.findProperty('imcMavenUser')
    def imcPass = System.getenv('IMC_MAVEN_PASSWORD') ?: project.findProperty('imcMavenPassword')
    if (imcUser && imcPass) {
        maven {
            name = 'ItMeCasey mirror'
            url = 'https://itmecasey.com/maven'
            credentials { username = imcUser; password = imcPass }
            content { includeGroup 'curse.maven' }
        }
    }
    maven {
        name = 'Cursemaven (fallback)'
        url = 'https://cursemaven.com'
        content { includeGroup 'curse.maven' }
    }
}

%(window)sdef viewerFiles = %(files)s
%(compile)sif (project.hasProperty('viewers')) {
    dependencies {
        project.property('viewers').split(',').each { name -> runtimeOnly %(dep)s }
    }
}
"""


def main():
    for project, base in (("barelypowered", ROOT), ("barelycables", ROOT / "barelycables")):
        for loader in ("neoforge", "forge"):
            for mc, files in VIEWERS[loader].items():
                layer = base / f"{loader}-{mc}"
                gradle = layer / "build.gradle"
                text = gradle.read_text(encoding="utf-8")
                if MARK in text:
                    text = text[: text.index(MARK)].rstrip() + "\n"
                files_groovy = "[" + ", ".join(f"{k}: '{v}'" for k, v in files.items()) + "]"
                compile_line = ""
                if loader == "neoforge":
                    compile_line = f"dependencies {{\n    compileOnly 'curse.maven:jade-324717:{JADE[mc]}'\n}}\n"
                    tpl = (ROOT / "scripts" / "templates" / ("BarelyPoweredJadePlugin.java.tpl" if project == "barelypowered"
                                                             else "BarelyCablesJadePlugin.java.tpl")).read_text(encoding="utf-8")
                    new = not mc == "1.21.1"
                    out = (tpl.replace("__ID__", "Identifier" if new else "ResourceLocation")
                           .replace("__HELPERS__", HELPERS_NEW if new else HELPERS_OLD))
                    pkg = f"com/itmecasey/{project}/jade"
                    target = layer / "src/main/java" / pkg / ("BarelyPoweredJadePlugin.java" if project == "barelypowered"
                                                             else "BarelyCablesJadePlugin.java")
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(out, encoding="utf-8")
                gradle.write_text(text + "\n" + BLOCK % {"files": files_groovy, "compile": compile_line,
                                                                "window": WINDOW_NEO if loader == "neoforge" else "",
                                                                "dep": 'fg.deobf("curse.maven:${viewerFiles[name.trim()]}")' if (loader == "forge" and mc == "1.21.1")
                                                                else '"curse.maven:${viewerFiles[name.trim()]}"'}, encoding="utf-8")
                print("patched", layer.relative_to(ROOT))


if __name__ == "__main__":
    main()
